// ── Placeholder fill (Template → Case document) ───────────────────────────────

/**
 * Read a saved template HTML (from TemplateEditor / disk) and fill in the
 * known case-specific placeholder marks with real values from the case.
 * Unknown marks (e.g. [причина], [день.месяц.год]) stay highlighted for the
 * judge to fill in manually.
 *
 * This is the bridge between "Шаблоны документов" (source of truth) and
 * "Иски" (per-case copy).
 */
export function fillTemplatePlaceholders(html: string, c: Case, settings: Settings): string {
  const judge  = judgeFullName(settings)
  const date   = today()
  const pPlain = preamblePlaintiff(c)
  const dFull  = preambleDefendants(c)   // "против сотрудника X (далее - ответчик №1)"

  /** Replace <mark class="doc-placeholder">[KEY]</mark> with a plain-text value */
  function replaceMark(key: string, value: string): void {
    if (!value) return
    const esc = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    html = html.replace(
      new RegExp(`<mark[^>]*class="doc-placeholder"[^>]*>\\[${esc}\\]<\\/mark>`, 'gi'),
      value
    )
  }

  // ── 1. Case number & date ───────────────────────────────────────────────────
  replaceMark('НОМЕР ДЕЛА',  c.caseNumber)
  replaceMark('Номер иска',  c.caseNumber)
  replaceMark('ДАТА',        date)

  // ── 2. Plaintiff & defendant short-name placeholders ─────────────────────────
  replaceMark('Имя Фамилия истца', pPlain)
  replaceMark('ИСТЕЦ',             pPlain)
  // Simple defendant name used when judge manually inserts [ОТВЕТЧИК]
  const dShort = c.participants.filter(p => p.role === 'defendant')
    .map(p => `${p.firstName} ${p.lastName}`.trim())
    .join(', ') || c.defendant
  if (dShort) replaceMark('ОТВЕТЧИК', dShort)

  // ── 3. Defendant preamble — CONTEXTUAL replacement ───────────────────────────
  //
  // getTemplatePreview() generates:
  //   "...от гражданина <strong>[Имя Фамилия истца]</strong> (далее - истец)
  //    против <mark>[Гос. структура / Имя Фамилия / Жетон ответчика]</mark>
  //    (далее - ответчик №1),"
  //
  // We must match the surrounding "против" + "(далее - ответчик №1)" and
  // replace the WHOLE pattern with preambleDefendants(c), which already
  // includes "против ..." and "(далее - ответчик №N)".
  const DEF_MARK_KEY = 'Гос\\. структура \\/ Имя Фамилия \\/ Жетон ответчика'
  const contextualPattern = new RegExp(
    `против\\s+<mark[^>]*class="doc-placeholder"[^>]*>\\[${DEF_MARK_KEY}\\]<\\/mark>\\s*\\(далее\\s*-\\s*ответчик\\s*№1\\)`,
    'gi'
  )
  if (contextualPattern.test(html)) {
    html = html.replace(contextualPattern, dFull)
  } else {
    // Fallback: just replace the bare mark (template was edited manually)
    replaceMark('Гос. структура / Имя Фамилия / Жетон ответчика', dFull)
  }

  // ── 4. Defendant organisation name inside audit blocks ────────────────────
  //      [Гос. структура] marks appear in the per-defendant blocks (point 4).
  //      Replace with the first defendant's organisation, or all orgs joined.
  const defOrgs = c.participants
    .filter(p => p.role === 'defendant')
    .map(p => p.position)
    .filter(Boolean) as string[]

  if (defOrgs.length === 1) {
    replaceMark('Гос. структура', defOrgs[0])
  } else if (defOrgs.length > 1) {
    // Replace sequentially: first [Гос. структура] → first org, second → second org
    defOrgs.forEach(org => {
      const esc = 'Гос\\. структура'
      html = html.replace(
        new RegExp(`<mark[^>]*class="doc-placeholder"[^>]*>\\[${esc}\\]<\\/mark>`, 'i'),
        org
      )
    })
  }
  // (if no defendants, [Гос. структура] stays highlighted)

  // ── 5. Judge (only fills if the template was saved with empty settings) ────
  replaceMark('Имя Фамилия судьи', judge)
  replaceMark('СУДЬЯ',             judge)

  return html
}

