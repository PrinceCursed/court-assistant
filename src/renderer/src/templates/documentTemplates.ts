export function htmlToBBCode(html: string): string {
  const div = document.createElement('div')
  div.innerHTML = html

  function processNode(node: Node): string {
    if (node.nodeType === Node.TEXT_NODE) return node.textContent || ''
    if (node.nodeType !== Node.ELEMENT_NODE) return ''

    const el = node as HTMLElement
    const tag = el.tagName.toLowerCase()
    const children = Array.from(el.childNodes).map(processNode).join('')

    switch (tag) {
      case 'mark':
        if (el.classList.contains('doc-placeholder')) return children
        return children
      case 'strong': case 'b': return `[B]${children}[/B]`
      case 'em': case 'i':     return `[I]${children}[/I]`
      case 'u':                return `[U]${children}[/U]`
      case 's': case 'strike': return `[S]${children}[/S]`
      case 'h1': return `[SIZE=6][B]${children}[/B][/SIZE]\n`
      case 'h2': return `[SIZE=5][B]${children}[/B][/SIZE]\n`
      case 'h3': return `[SIZE=4][B]${children}[/B][/SIZE]\n`
      case 'blockquote': return `[QUOTE]${children}[/QUOTE]\n`
      case 'ul': return `[LIST]\n${children}[/LIST]\n`
      case 'ol': return `[LIST=1]\n${children}[/LIST]\n`
      case 'li': return `[*]${children}\n`
      case 'br': return '\n'
      case 'p': {
        const align = el.style.textAlign
        if (align === 'center') return `[CENTER]${children}[/CENTER]\n`
        if (align === 'right')  return `[RIGHT]${children}[/RIGHT]\n`
        return children + '\n'
      }
      case 'div': {
        if (el.classList.contains('doc-section')) return `\n[B]${children}[/B]\n`
        if (el.classList.contains('page-break'))  return '\n[HR]\n'
        const align = el.style.textAlign
        if (align === 'center') return `[CENTER]${children}[/CENTER]\n`
        return children + '\n'
      }
      case 'hr': return '[HR]\n'
      default:   return children
    }
  }

  return processNode(div).replace(/\n{3,}/g, '\n\n').trim()
}
